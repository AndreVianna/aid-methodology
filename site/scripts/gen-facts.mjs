// gen-facts.mjs - writes the skill, agent and settings pages of the site from canonical/.
// Usage: node site/scripts/gen-facts.mjs [--check] [--canonical <dir>] [--out <dir>]
// Write mode saves the missing or stale pages; --check writes nothing and reports drift.
// Exit codes: 0 up to date or written; 1 drift (--check only); 2 input, usage or crash.
// Reads only canonical/{skills,agents}, shortcut-catalog.yml and settings.yml. Run by hand
// after a canonical/ change and commit the output; it is not part of the build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

/** @typedef {{ name: string, purpose: string, rest: string, argumentHint: string|null,
 *              allowedTools: string[], order: number, group: Group }} Skill */
/** @typedef {{ id: string, label: string, anchor: string, blurb: string, ordered: boolean,
 *              fixed: string[]|null, skills: Skill[] }} Group */
/** @typedef {{ name: string, description: string, tier: 'large'|'medium'|'small',
 *              tools: string[] }} Agent */
/** @typedef {{ key: string, value: string, description: string,
 *              kind: 'key'|'section'|'unseeded' }} SettingRow */
/** @typedef {Map<string, string>} PageSet  // out-relative POSIX path -> exact file content */

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const TIERS = ['large', 'medium', 'small'];
const BLOB = 'https://github.com/AndreVianna/aid-methodology/blob/master';
const MARK = '<!-- generated by site/scripts/gen-facts.mjs from';
// The only hand data: per group, never per skill. A null `fixed` means a catalog group (id = catalog code).

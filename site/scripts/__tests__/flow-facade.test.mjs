// ── FAC-2: every classifier shape now charts (task-037) ────────────────────
//
// These three tests previously asserted that `buildFlowChart` THROWS for the two
// doorway shapes, which was correct while only feature-003's three extractors were
// wired. task-037 adds the two doorway rows, and making every shape chart is the
// point of that task — FR-2 requires no skill page to be left with an unfilled body
// slot. Re-scoped rather than deleted: the same skills are still named, and the
// assertion is inverted to the behaviour that is now contractual.

describe('buildFlowChart — every shape charts (FAC-2, re-scoped by task-037)', () => {
  it('charts a sibling-doorway skill (aid-document-architecture)', () => {
    const chart = buildFlowChart({ name: 'aid-document-architecture', dir: REPO_ROOT });
    expect(chart.shape).toBe('sibling-doorway');
    expect(chart.nodes.length).toBeGreaterThan(1);   // prefix + spliced parent spine
    expect(chart.entries).toEqual([chart.nodes[0].id]);
  });

  it('charts an engine-doorway skill (aid-add)', () => {
    const chart = buildFlowChart({ name: 'aid-add', dir: REPO_ROOT });
    expect(chart.shape).toBe('engine-doorway');
    expect(chart.nodes[0].name).toBe('aid-add');
    // The doorway plus the eight engine-segment nodes.
    // 9, not 10: the engine spine lost its GATE circuit-breaker node when work-003
    // delivery-012 moved the fix loop and breaker into /aid-deep-review.
    expect(chart.nodes).toHaveLength(9);
  });

  it('all five classifier shapes chart — the contract that replaced the throw', () => {
    // The old pre-switch shape guard is gone, not merely widened. With every enum value
    // dispatching, no input could reach it, and the switch's `default:` arm already
    // throws the same error for a future sixth shape. A test asserting an unreachable
    // throw would be a test that cannot fail; this asserts the property that actually
    // holds and that FR-2 depends on.
    //
    // A first attempt tried to reach the guard with a nonexistent skill name; that
    // throws ENOENT from the file read long before any classification happens, which is
    // a different guard entirely.
    const byShape = new Map();
    for (const name of ['aid-review', 'aid-config', 'aid-summarize', 'aid-add', 'aid-test-security']) {
      const chart = buildFlowChart({ name, dir: REPO_ROOT });
      byShape.set(chart.shape, name);
    }
    expect([...byShape.keys()].sort()).toEqual([
      'dispatch-table', 'engine-doorway', 'inline-states', 'residual', 'sibling-doorway',
    ]);
  });
});


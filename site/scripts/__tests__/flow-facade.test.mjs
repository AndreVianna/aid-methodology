// ── FAC-5: provider render() ──────────────────────────────────────────────

describe('flow-chart-authored provider — render() (FAC-5)', () => {
  const provider = BODY_PROVIDERS.find((p) => p.id === 'flow-chart-authored');

  it('emits ## Flow heading (derived skill — aid-review)', () => {
    // Mutation probe: change heading to ## Chart → not startsWith → fails.
    const skill = { dirName: 'aid-review', body: INLINE_BODY };
    const output = provider.render(skill);
    expect(output).toMatch(/^## Flow\n/);
  });

  it('emits a fenced mermaid code block (derived skill — aid-review)', () => {
    // Mutation probe: remove the triple-backtick fence → not to contain → fails.
    const skill = { dirName: 'aid-review', body: INLINE_BODY };
    const output = provider.render(skill);
    expect(output).toContain('```mermaid\n');
    expect(output).toContain('\n```\n');
  });

  it('does NOT emit an approximate notice for a derived skill (aid-review)', () => {
    // Mutation probe: always emit the notice → toContain fails (notice present when not expected).
    const skill = { dirName: 'aid-review', body: INLINE_BODY };
    const output = provider.render(skill);
    expect(output).not.toContain('Approximate:');
  });

  it('emits an approximate notice for an approximate skill (aid-config)', () => {
    // Mutation probe: remove the notice emission → not toContain → fails.
    const aidConfigBody = readSkillBody('aid-config');
    const skill = { dirName: 'aid-config', body: aidConfigBody };
    const output = provider.render(skill);
    expect(output).toContain('Approximate:');
  });

  it('approximate notice appears between ## Flow and the mermaid fence', () => {
    // Mutation probe: emit notice after the fence → indexOf(notice) < indexOf(fence).
    const aidConfigBody = readSkillBody('aid-config');
    const skill = { dirName: 'aid-config', body: aidConfigBody };
    const output = provider.render(skill);
    const headingIdx = output.indexOf('## Flow');
    const noticeIdx = output.indexOf('Approximate:');
    const fenceIdx = output.indexOf('```mermaid');
    expect(headingIdx).toBeGreaterThan(-1);
    expect(noticeIdx).toBeGreaterThan(headingIdx);
    expect(noticeIdx).toBeLessThan(fenceIdx);
  });

  it('output is LF-terminated', () => {
    // Mutation probe: forget trailing newline → not toMatch fails.
    const skill = { dirName: 'aid-review', body: INLINE_BODY };
    const output = provider.render(skill);
    expect(output).toMatch(/\n$/);
  });
});

// ── FAC-6: corpus-wide validation loop ────────────────────────────────────

describe('all authored skills — corpus validation (FAC-6)', () => {
  it('every authored skill builds and validates through buildFlowChart without throwing', () => {
    const authoredShapes = new Set(['dispatch-table', 'inline-states', 'residual']);
    const dirNames = readdirSync(CANONICAL_SKILLS_DIR).filter((d) =>
      existsSync(join(CANONICAL_SKILLS_DIR, d, 'SKILL.md'))
    );

    let authoredCount = 0;
    for (const dirName of dirNames) {
      const text = readFileSync(join(CANONICAL_SKILLS_DIR, dirName, 'SKILL.md'), 'utf8');
      const { bodyLines } = splitFrontmatter(text, `canonical/skills/${dirName}/SKILL.md`);
      const body = bodyLines.join('\n');
      const { shape } = classifySkill({ name: dirName, dir: REPO_ROOT, frontmatter: {}, body });

      if (!authoredShapes.has(shape)) continue;

      let chart;
      try {
        chart = buildFlowChart({ name: dirName, dir: REPO_ROOT });
      } catch (e) {
        throw new Error(`buildFlowChart failed for ${dirName}: ${e.message}`);
      }

      // Per-skill structural assertions — catching issues a flat "not.toThrow" misses.
      expect(chart.skill, `${dirName}: chart.skill`).toBe(dirName);
      expect(chart.nodes.length, `${dirName}: chart must have nodes`).toBeGreaterThan(0);
      expect(
        ['derived', 'approximate'],
        `${dirName}: confidence must be derived or approximate`
      ).toContain(chart.confidence);

      const { ok, errors } = validateChart(chart);
      expect(ok, `${dirName}: validateChart — ${errors[0] ?? ''}`).toBe(true);

      const mermaid = renderMermaid(chart);
      expect(mermaid, `${dirName}: mermaid output must be non-empty`).toBeTruthy();

      authoredCount += 1;
    }

    // Guard: the loop must have exercised at least some authored skills.
    expect(authoredCount, 'at least one authored skill must be validated').toBeGreaterThan(0);
  });
});
